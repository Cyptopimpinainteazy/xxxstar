pub struct ComplianceGuardAgent;
impl ComplianceGuardAgent {
    pub fn new()->Self{Self}
    pub fn generate(&self,plan:&ArchitecturePlan,prompt:&str)->Result<ComplianceReport,FoundryError>{
        info!("ComplianceGuardAgent: checking compliance for {}",plan.name);
        let pl=prompt.to_lowercase();let mut w=Vec::new();let mut v=Vec::new();let mut rj=Vec::new();let mut sd=false;let mut tv=false;
        for kw in &["rug","pump and dump","guaranteed returns","get rich quick","ponzi","pyramid","money laundering"]{if pl.contains(kw){sd=true;v.push(format!("Scam: '{}'",kw));}}
        for kw in &["illegal","drug","weapon","terrorism","fraud","gambling","unlicensed","hacking","malware"]{if pl.contains(kw){tv=true;v.push(format!("Illegal: '{}'",kw));}}
        for kw in &["fake","impersonate","deceive","mislead","spoof","phishing"]{if pl.contains(kw){w.push(format!("Deceptive: '{}'",kw));}}
        for kw in &["north korea","iran","syria","cuba","crimea"]{if pl.contains(kw){rj.push(kw.to_string());v.push(format!("Restricted: '{}'",kw));}}
        for nm in &["uniswap","pancakeswap","opensea","binance","coinbase","metamask"]{if plan.name.to_lowercase().contains(nm){w.push(format!("Impersonation: '{}'",nm));}}
        let passed=v.is_empty();
        let cs=if passed{100u8.saturating_sub((w.len()as u8).saturating_mul(10))}else{0};
        Ok(ComplianceReport{passed,warnings:w,violations:v,restricted_jurisdictions:rj,scam_detected:sd,terms_violation:tv,compliance_score:cs})
    }
}
impl Default for ComplianceGuardAgent{fn default()->Self{Self::new()}}

