pub struct ContractEngineerAgent;
impl ContractEngineerAgent {
    pub fn new()->Self{Self}
    pub fn generate(&self,plan:&ArchitecturePlan)->Result<ContractOutput,FoundryError>{
        info!("ContractEngineerAgent: generating contracts for {}",plan.name);
        let mut contracts=HashMap::new();let mut abi=HashMap::new();let mut bytecode_hashes=HashMap::new();let mut deployment_order=Vec::new();let mut constructor_args=HashMap::new();
        for cn in &plan.required_contracts{
            let src=self.generate_contract_source(cn,&plan.dapp_type);
            contracts.insert(cn.clone(),src.clone());
            abi.insert(cn.clone(),self.generate_abi(cn));
            bytecode_hashes.insert(cn.clone(),self.compute_bytecode_hash(&src));
            deployment_order.push(cn.clone());
            constructor_args.insert(cn.clone(),vec![]);
        }
        Ok(ContractOutput{contracts,abi,bytecode_hashes,deployment_order,constructor_args})
    }
    fn generate_contract_source(&self,cn:&str,dt:&DAppType)->String{
        let ts=Utc::now().to_rfc3339();
        format!("// SPDX-License-Identifier: Apache-2.0\n// Auto-generated by X3 Foundry\n// {ts}\n// {dt}\n// {cn}\npragma solidity ^0.8.20;\ncontract {cn}{{\naddress public owner;\nevent Init(address indexed o);\nmodifier onlyOwner(){{require(msg.sender==owner,\"Not owner\");_;}}\nconstructor(){{owner=msg.sender;emit Init(msg.sender);}}\nfunction getInfo()external view returns(string memory,address){{\nreturn(\"{cn}\",owner);\n}}\nreceive()external payable{{}}\nfallback()external payable{{}}\n}}",ts=ts,dt=dt.label(),cn=cn)
    }
    fn generate_abi(&self,cn:&str)->String{
        format!(r#"{{"cn":"{cn}","abi":[{{"type":"constructor","inputs":[],"stateMutability":"nonpayable"}},{{"type":"function","name":"owner","inputs":[],"outputs":[{{"type":"address"}}],"stateMutability":"view"}}]}}"#,cn=cn)
    }
    fn compute_bytecode_hash(&self,src:&str)->String{
        use sha2::{Digest,Sha256};let mut h=Sha256::new();h.update(src.as_bytes());hex::encode(h.finalize())
    }
}
impl Default for ContractEngineerAgent{fn default()->Self{Self::new()}}

