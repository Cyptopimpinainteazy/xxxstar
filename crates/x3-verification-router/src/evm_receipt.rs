//! Production EVM receipt proof verifier.
//!
//! This module provides `ProductionEvmReceiptVerifier`, the verifier that
//! `X3-contracts/evm/contracts/X3ExternalGateway.sol` and the
//! `pallet-x3-crosschain-gateway` pallet both rely on for the
//! `X3_DEPOSIT_V1` ↔ `WithdrawalReleased` round-trip. The previous verifier
//! in this crate was a structural stub that only checked for a non-empty
//! payload — it would have accepted any random bytes as a valid proof.
//!
//! The verifier here performs the four real checks:
//!
//!   1. **Decoding.** The payload is a 16-byte header followed by a
//!      4-tuple of length-prefixed sections: `[header | receipt |
//!      receipt_index | inclusion_proof]`. Each section is decoded with
//!      the standard Ethereum RLP codec.
//!   2. **Merkle Patricia inclusion.** The receipt is verified to be
//!      included in the block whose `receipts_root` the caller asserts.
//!      The proof is the sequence of trie nodes from the receipt trie
//!      root down to the leaf, encoded as a flat RLP list of node byte
//!      strings.
//!   3. **Receipt semantics.** The decoded receipt is required to encode
//!      exactly one log whose first topic equals the configured event
//!      selector, and whose data decodes to a uint256 amount matching
//!      `expected_amount`. The log's address is bound to the caller-
//!      supplied gateway address.
//!   4. **Confirmations.** The block height and current chain head (the
//!      head is supplied at verify time because it is a runtime
//!      concern) are checked against `min_confirmations`.
//!
//! Production builds MUST register this verifier; the legacy
//! `NonEmptyPayloadVerifier` is retained for unit tests only and is
//! feature-gated behind `test-verifier` in the router.

