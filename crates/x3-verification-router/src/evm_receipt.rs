// ── Light client header ────────────────────────────────────────────────────

/// A 256-byte decoded EIP-1186 block header. The verifier only consults
/// the `receipts_root` field but the full layout is preserved for
/// forward-compatibility.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EvmBlockHeader {
    pub parent_hash: [u8; 32],
    pub state_root: [u8; 32],
    pub receipts_root: [u8; 32],
    pub logs_bloom: Vec<u8>,
    pub number: u64,
    pub timestamp: u64,
}

impl EvmBlockHeader {
    /// Decode an RLP-encoded EIP-1186 block header. The header is encoded
    /// as a 15-element list; only the fields the verifier needs are
    /// decoded — the rest are skipped.
    pub fn decode(rlp: &[u8]) -> Result<Self, EvmReceiptError> {
        let s = rlp::Rlp::new(rlp);
        if !s.is_list() {
            return Err(EvmReceiptError::BadHeader);
        }
        let item_count = s.item_count().unwrap_or(0);
        if item_count < 15 {
            return Err(EvmReceiptError::BadHeader);
        }
        // The header's field order, per the yellow paper: parentHash(0),
        // sha3Uncles(1), beneficiary(2), stateRoot(3), transactionsRoot(4),
        // receiptsRoot(5), logsBloom(6), difficulty(7), number(8), gasLimit(9),
        // gasUsed(10), timestamp(11), extraData(12), mixHash(13), nonce(14), then
        // the fork additions (baseFeePerGas, withdrawalsRoot, blobGasUsed, …).
        //
        // These reads used to be 1/2/3/4 for state root, receipts root, bloom and
        // difficulty — the *abbreviated* field list this function's doc comment
        // carried, not the header's real layout. `receipts_root` was therefore the
        // `beneficiary` address, so the receipts-trie walk `validate` performs
        // could never match a genuine header: the verifier rejected every real
        // proof, and no test noticed because none of them got past decoding
        // (TICKET-064).
        let parent_hash: Vec<u8> = s.at(0)?.as_val()?;
        let state_root: Vec<u8> = s.at(3)?.as_val()?;
        let receipts_root: Vec<u8> = s.at(5)?.as_val()?;
        let logs_bloom: Vec<u8> = s.at(6)?.as_val()?;
        let number_bytes: Vec<u8> = s.at(8)?.as_val()?;
        let timestamp_bytes: Vec<u8> = s.at(11)?.as_val()?;
        Ok(Self {
            parent_hash: bytes32(&parent_hash)?,
            state_root: bytes32(&state_root)?,
            receipts_root: bytes32(&receipts_root)?,
            logs_bloom,
            number: decode_u64(&number_bytes),
            timestamp: decode_u64(&timestamp_bytes),
        })
    }
}

// ── Receipt ────────────────────────────────────────────────────────────────

/// Decoded EIP-2930 / legacy transaction receipt. Only the fields the
/// verifier needs are decoded.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EvmReceipt {
    /// True iff the receipt is the post-Byzantium (status-code) form.
    pub status: bool,
    pub cumulative_gas_used: u64,
    pub logs: Vec<EvmLog>,
}

/// Single EVM log entry.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct EvmLog {
    pub address: [u8; 20],
    pub topics: Vec<[u8; 32]>,
    pub data: Vec<u8>,
}

impl EvmReceipt {
    /// Decode an RLP-encoded legacy or EIP-2930 receipt. The receipt is a
    /// list of three fields: status (post-Byzantium) or root (pre-Byzantium),
    /// cumulative_gas_used, logs. We require the status form because the
    /// X3 gateway emits `DepositLocked` (success) and reverts on failure,
    /// so we never accept a pre-Byzantium root-form receipt.
    pub fn decode(rlp: &[u8]) -> Result<Self, EvmReceiptError> {
        // EIP-2718: a typed receipt is `type || rlp(payload)` — `0x01` for
        // EIP-2930, `0x02` for EIP-1559, `0x03` for EIP-4844 — and the type byte
        // is part of the consensus encoding, so it is skipped here rather than
        // stripped from the bytes the caller keeps (the trie leaf commits to the
        // whole thing, type byte included). Refusing typed receipts meant this
        // verifier could only ever accept a leg whose transaction was sent by a
        // legacy signer; every wallet since 2021 emits `0x02`.
        let body = match rlp.first() {
            Some(byte) if TYPED_RECEIPT_TYPES.contains(byte) => &rlp[1..],
            _ => rlp,
        };
        let s = rlp::Rlp::new(body);
        if !s.is_list() {
            return Err(EvmReceiptError::BadReceipt);
        }
        if s.item_count().unwrap_or(0) < 3 {
            return Err(EvmReceiptError::BadReceipt);
        }
        let status_byte: u8 = s.at(0)?.as_val()?;
        let cumulative: Vec<u8> = s.at(1)?.as_val()?;
        let logs_rlp = s.at(2)?;
        let mut logs = Vec::with_capacity(logs_rlp.item_count().unwrap_or(0));
        for log_rlp in logs_rlp.iter() {
            logs.push(EvmLog::decode(log_rlp.as_raw())?);
        }
        Ok(Self {
            status: status_byte != 0,
            cumulative_gas_used: decode_u64(&cumulative),
            logs,
        })
    }
}

impl EvmLog {
    pub fn decode(rlp: &[u8]) -> Result<Self, EvmReceiptError> {
        let s = rlp::Rlp::new(rlp);
        if !s.is_list() {
            return Err(EvmReceiptError::BadReceipt);
        }
        let address_bytes: Vec<u8> = s.at(0)?.as_val()?;
        if address_bytes.len() != 20 {
            return Err(EvmReceiptError::BadReceipt);
        }
        let mut address = [0u8; 20];
        address.copy_from_slice(&address_bytes);
        let topics_rlp = s.at(1)?;
        let mut topics = Vec::with_capacity(topics_rlp.item_count().unwrap_or(0));
        for t in topics_rlp.iter() {
            let v: Vec<u8> = t.as_val()?;
            topics.push(bytes32(&v)?);
        }
        let data: Vec<u8> = s.at(2)?.as_val()?;
        Ok(Self {
            address,
            topics,
            data,
        })
    }
}

// ── Receipt trie Merkle Patricia proof ─────────────────────────────────────

/// Verify that a (key, value) pair is included in a Merkle Patricia trie
/// with the given root. `proof` is the flat list of trie nodes from root
/// to leaf, in RLP. `key` is the raw byte path; for the receipts trie
/// the path is `rlp(index)`.
pub fn verify_merkle_patricia_proof(
    root: &[u8; 32],
    key: &[u8],
    value: Option<&[u8]>,
    proof: &[u8],
) -> Result<(), EvmReceiptError> {
    let proof_rlp = rlp::Rlp::new(proof);
    if !proof_rlp.is_list() {
        return Err(EvmReceiptError::BadProof);
    }
    let mut nodes: Vec<Vec<u8>> = Vec::with_capacity(proof_rlp.item_count().unwrap_or(0));
    for n in proof_rlp.iter() {
        let v: Vec<u8> = n.as_val()?;
        nodes.push(v);
    }
    if nodes.is_empty() {
        return Err(EvmReceiptError::BadProof);
    }

    let mut expected_hash = *root;
    let mut nibbles = Nibbles::from_bytes(key);
    let last = nodes.len() - 1;
    for (i, node) in nodes.iter().enumerate() {
        if keccak256_bytes(node) != expected_hash {
            return Err(EvmReceiptError::InclusionFailed);
        }
        let r = rlp::Rlp::new(node);
        if !r.is_list() {
            return Err(EvmReceiptError::BadProof);
        }
        let item_count = r.item_count().unwrap_or(0);
        if item_count == 17 {
            // Branch node.
            //
            // A branch is a real node in the middle of the walk, not a terminal
            // one. This used to require `i == last`, which made every proof for a
            // block with more than one transaction unverifiable: the path from the
            // receipts root to a receipt is *root branch → … → leaf*, so the branch
            // was never last and every such proof came back `BadProof`. The only
            // proof the walk accepted was a single leaf at the root — a one-receipt
            // block — which is why this survived: no live path had ever fed it a
            // proof built from a real block.
            if nibbles.is_empty() {
                let stored_value: Vec<u8> = r.at(16)?.as_val()?;
                return if Some(stored_value.as_slice()) == value {
                    Ok(())
                } else {
                    Err(EvmReceiptError::InclusionFailed)
                };
            }
            let n = nibbles.pop_front();
            let child: Vec<u8> = r.at(n as usize)?.as_val()?;
            if child.is_empty() {
                return Err(EvmReceiptError::InclusionFailed);
            }
            if child.len() != 32 {
                // A child whose RLP is shorter than 32 bytes is embedded in the
                // branch rather than referenced by hash. Real receipts are far
                // larger than that, so this is refused rather than mis-walked.
                return Err(EvmReceiptError::BadProof);
            }
            expected_hash = bytes32_const(&child);
        } else if item_count == 2 {
            // Leaf or extension.
            let path: Vec<u8> = r.at(0)?.as_val()?;
            let path_nibs = Nibbles::from_compact(&path);
            if path_nibs.is_empty() {
                if i != last {
                    return Err(EvmReceiptError::BadProof);
                }
                let stored_value: Vec<u8> = r.at(1)?.as_val()?;
                return if Some(stored_value.as_slice()) == value {
                    Ok(())
                } else {
                    Err(EvmReceiptError::InclusionFailed)
                };
            }
            let first_nibble = path[0] >> 4;
            // Hex-prefix flags (yellow paper appendix C): the first nibble is
            // `2 * leaf + odd`. So the *low* bit says whether the path length is
            // odd and the second bit says leaf-vs-extension. This read `& 1`,
            // which is the odd/even bit, so a leaf whose remaining path happened
            // to be an odd number of nibbles was walked as an extension — its
            // receipt read as a child hash — and refused with `BadProof`. Keys
            // are `rlp(index)`, whose nibble length is always even, so the bug
            // only showed on leaves that sit at an odd depth: which is most
            // leaves in any block with more than one transaction.
            let is_leaf = first_nibble & 0x2 != 0;
            if is_leaf {
                // Leaf.
                if i != last {
                    return Err(EvmReceiptError::BadProof);
                }
                if !path_nibs.is_suffix(&nibbles) {
                    return Err(EvmReceiptError::InclusionFailed);
                }
                let stored_value: Vec<u8> = r.at(1)?.as_val()?;
                return if Some(stored_value.as_slice()) == value {
                    Ok(())
                } else {
                    Err(EvmReceiptError::InclusionFailed)
                };
            }
            // Extension.
            if i == last {
                return Err(EvmReceiptError::BadProof);
            }
            if !path_nibs.is_suffix(&nibbles) {
                return Err(EvmReceiptError::InclusionFailed);
            }
            let child: Vec<u8> = r.at(1)?.as_val()?;
            if child.is_empty() {
                return Err(EvmReceiptError::InclusionFailed);
            }
            if child.len() != 32 {
                return Err(EvmReceiptError::BadProof);
            }
            expected_hash = bytes32_const(&child);
            nibbles = nibbles.consume(path_nibs.len());
        } else {
            return Err(EvmReceiptError::BadProof);
        }
    }
    Err(EvmReceiptError::InclusionFailed)
}

fn bytes32_const(b: &[u8]) -> [u8; 32] {
    let mut out = [0u8; 32];
    let len = b.len().min(32);
    out[..len].copy_from_slice(&b[..len]);
    out
}

fn keccak256_bytes(input: &[u8]) -> [u8; 32] {
    let mut k = Keccak::v256();
    let mut out = [0u8; 32];
    k.update(input);
    k.finalize(&mut out);
    out
}

// ── Compact path encoding & nibble helpers ─────────────────────────────────

#[derive(Debug, Clone, PartialEq, Eq)]
struct Nibbles {
    bytes: Vec<u8>,
    first_half: Option<u8>,
}

impl Nibbles {
    fn from_bytes(b: &[u8]) -> Self {
        let mut bytes = Vec::with_capacity(b.len() * 2);
        for byte in b {
            bytes.push(byte >> 4);
            bytes.push(byte & 0x0F);
        }
        Self {
            bytes,
            first_half: None,
        }
    }

    fn from_compact(compact: &[u8]) -> Self {
        if compact.is_empty() {
            return Self {
                bytes: Vec::new(),
                first_half: None,
            };
        }
        let flag = compact[0] >> 4;
        let odd = flag & 1 == 1;
        let mut bytes = Vec::with_capacity(compact.len() * 2);
        if odd {
            bytes.push(compact[0] & 0x0F);
        }
        for byte in &compact[1..] {
            bytes.push(byte >> 4);
            bytes.push(byte & 0x0F);
        }
        Self {
            bytes,
            first_half: None,
        }
    }

    fn is_empty(&self) -> bool {
        self.bytes.is_empty() && self.first_half.is_none()
    }

    fn pop_front(&mut self) -> u8 {
        if let Some(n) = self.first_half.take() {
            return n;
        }
        if self.bytes.is_empty() {
            0
        } else {
            self.bytes.remove(0)
        }
    }

    fn consume(mut self, n: usize) -> Self {
        for _ in 0..n {
            if self.first_half.is_some() {
                self.first_half = None;
            } else if !self.bytes.is_empty() {
                self.bytes.remove(0);
            }
        }
        self
    }

    fn len(&self) -> usize {
        self.bytes.len() + if self.first_half.is_some() { 1 } else { 0 }
    }

    fn is_suffix(&self, prefix: &Nibbles) -> bool {
        let p = prefix.len();
        let s = self.len();
        if s > p {
            return false;
        }
        let mut a = self.clone();
        let mut b = prefix.clone();
        for _ in 0..s {
            let x = a.pop_front();
            let y = b.pop_front();
            if x != y {
                return false;
            }
        }
        true
    }
}

/// The EIP-2718 receipt type bytes this code understands.
///
/// A typed receipt is `type || rlp(payload)`: EIP-2930 (`0x01`), EIP-1559
/// (`0x02`), EIP-4844 (`0x03`) and EIP-7702 (`0x04`). They share the same
/// payload shape as a legacy receipt — `[status, cumulativeGasUsed, logsBloom,
/// logs]` — which is all the structural checks look at. The list is explicit
/// rather than a range so an unknown type is refused instead of walked with
/// assumptions borrowed from a different one.
pub const TYPED_RECEIPT_TYPES: [u8; 4] = [0x01, 0x02, 0x03, 0x04];

// ── Receipts-trie construction ─────────────────────────────────────────────
//
// The verifier above answers "is this receipt in the tree with this root?". This
// section builds the other side of that question: given a block's receipts, the
// trie root (to compare against the header's `receiptsRoot`) and the inclusion
// proof for one of them.
//
// It belongs in this crate because the receipts trie is a wire format, and a
// producer that disagrees with the verifier in one detail (a different
// hex-prefix flag, the key encoded as a list instead of `rlp(index)`) produces
// proofs that never verify — with no way to tell which side is wrong. Here the
// two are tested against each other, and both are tested against a real block.

/// The root of an empty receipts trie: `keccak256(rlp(""))`, which is what a
/// block with no transactions carries.
pub const EMPTY_RECEIPTS_TRIE_ROOT: [u8; 32] = [
    0x56, 0xe8, 0x1f, 0x17, 0x1b, 0xcc, 0x55, 0xa6, 0xff, 0x83, 0x45, 0xe6, 0x92, 0xc0, 0xf8, 0x6e,
    0x5b, 0x48, 0xe0, 0x1b, 0x99, 0x6c, 0xad, 0xc0, 0x01, 0x62, 0x2f, 0xb5, 0xe3, 0x63, 0xb4, 0x21,
];

enum TrieNode {
    Leaf {
        path: Vec<u8>,
        value: Vec<u8>,
    },
    Extension {
        path: Vec<u8>,
        child: Box<TrieNode>,
    },
    Branch {
        children: [Option<Box<TrieNode>>; 16],
        value: Option<Vec<u8>>,
    },
}

/// Hex-prefix encoding of a nibble path (yellow paper appendix C).
fn hex_prefix(path: &[u8], leaf: bool) -> Vec<u8> {
    let odd = path.len() % 2 == 1;
    let flag = if leaf { 0x20 } else { 0x00 };
    let mut out = Vec::with_capacity(path.len() / 2 + 1);
    if odd {
        out.push(flag | 0x10 | path[0]);
        for pair in path[1..].chunks(2) {
            out.push((pair[0] << 4) | pair[1]);
        }
    } else {
        out.push(flag);
        for pair in path.chunks(2) {
            out.push((pair[0] << 4) | pair[1]);
        }
    }
    out
}

fn nibbles(bytes: &[u8]) -> Vec<u8> {
    let mut out = Vec::with_capacity(bytes.len() * 2);
    for byte in bytes {
        out.push(byte >> 4);
        out.push(byte & 0x0F);
    }
    out
}

fn common_prefix_len(entries: &[(Vec<u8>, Vec<u8>)]) -> usize {
    let mut len = entries[0].0.len();
    for (key, _) in &entries[1..] {
        let mut shared = 0;
        while shared < len && shared < key.len() && key[shared] == entries[0].0[shared] {
            shared += 1;
        }
        len = shared;
    }
    len
}

fn build_node(entries: &[(Vec<u8>, Vec<u8>)]) -> Option<TrieNode> {
    match entries.len() {
        0 => None,
        1 => Some(TrieNode::Leaf {
            path: entries[0].0.clone(),
            value: entries[0].1.clone(),
        }),
        _ => {
            let shared = common_prefix_len(entries);
            if shared > 0 {
                let rest: Vec<(Vec<u8>, Vec<u8>)> = entries
                    .iter()
                    .map(|(key, value)| (key[shared..].to_vec(), value.clone()))
                    .collect();
                let child = build_node(&rest)?;
                return Some(TrieNode::Extension {
                    path: entries[0].0[..shared].to_vec(),
                    child: Box::new(child),
                });
            }

            let mut children: [Option<Box<TrieNode>>; 16] =
                core::array::from_fn(|_| Option::None);
            let mut value: Option<Vec<u8>> = Option::None;
            for (key, entry_value) in entries {
                let Some(first) = key.first().copied() else {
                    value = Some(entry_value.clone());
                    continue;
                };
                let group: Vec<(Vec<u8>, Vec<u8>)> = entries
                    .iter()
                    .filter(|(other, _)| other.first().copied() == Some(first))
                    .map(|(other, item)| (other[1..].to_vec(), item.clone()))
                    .collect();
                children[first as usize] = Some(Box::new(build_node(&group)?));
            }
            Some(TrieNode::Branch { children, value })
        }
    }
}

fn encode_node(node: &TrieNode) -> Vec<u8> {
    match node {
        TrieNode::Leaf { path, value } => {
            let mut stream = rlp::RlpStream::new_list(2);
            stream.append(&hex_prefix(path, true));
            stream.append(value);
            stream.out().to_vec()
        }
        TrieNode::Extension { path, child } => {
            let encoded_child = encode_node(child);
            let mut stream = rlp::RlpStream::new_list(2);
            stream.append(&hex_prefix(path, false));
            // A child whose RLP is at least 32 bytes is referenced by its hash;
            // anything shorter is embedded. `verify_merkle_patricia_proof` accepts
            // only the hash form, which is also the only form real receipts
            // produce: every leaf carries a whole receipt.
            if encoded_child.len() >= 32 {
                stream.append(&keccak256_bytes(&encoded_child).to_vec());
            } else {
                stream.append_raw(&encoded_child, 1);
            }
            stream.out().to_vec()
        }
        TrieNode::Branch { children, value } => {
            let mut stream = rlp::RlpStream::new_list(17);
            for child in children.iter() {
                match child {
                    Option::None => {
                        stream.append_empty_data();
                    }
                    Option::Some(child) => {
                        let encoded_child = encode_node(child);
                        if encoded_child.len() >= 32 {
                            stream.append(&keccak256_bytes(&encoded_child).to_vec());
                        } else {
                            stream.append_raw(&encoded_child, 1);
                        }
                    }
                }
            }
            match value {
                Option::Some(value) => {
                    stream.append(value);
                }
                Option::None => {
                    stream.append_empty_data();
                }
            }
            stream.out().to_vec()
        }
    }
}

fn entries_for(receipts: &[Vec<u8>]) -> Vec<(Vec<u8>, Vec<u8>)> {
    receipts
        .iter()
        .enumerate()
        .map(|(index, receipt)| {
            (
                nibbles(&receipt_trie_key(index as u64)),
                receipt.clone(),
            )
        })
        .collect()
}

/// The receipts-trie root of a block's receipts, in the order the block listed
/// them.
///
/// This is the value a prover compares against the block header's
/// `receiptsRoot` before it hands a proof to anyone: if they differ, the trie was
/// built over the wrong receipts (or the encoding is wrong), and no proof
/// produced from it can verify.
pub fn receipts_trie_root(receipts: &[Vec<u8>]) -> Result<[u8; 32], EvmReceiptError> {
    if receipts.is_empty() {
        return Ok(EMPTY_RECEIPTS_TRIE_ROOT);
    }
    let entries = entries_for(receipts);
    let root = build_node(&entries).ok_or(EvmReceiptError::BadProof)?;
    Ok(keccak256_bytes(&encode_node(&root)))
}

fn collect_path_nodes(node: &TrieNode, path: &[u8], nodes: &mut Vec<Vec<u8>>) {
    nodes.push(encode_node(node));
    match node {
        TrieNode::Leaf { .. } => {}
        TrieNode::Extension { path: skip, child } => {
            let next = if path.len() >= skip.len() {
                &path[skip.len()..]
            } else {
                &[]
            };
            collect_path_nodes(child, next, nodes);
        }
        TrieNode::Branch { children, .. } => {
            if let Some(first) = path.first() {
                if let Option::Some(child) = &children[*first as usize] {
                    collect_path_nodes(child, &path[1..], nodes);
                }
            }
        }
    }
}

/// The Merkle-Patricia inclusion proof for one receipt of a block, as the flat
/// RLP list of node byte strings that [`verify_merkle_patricia_proof`] expects.
///
/// `receipt_index` is the index the block listed the receipt at: the trie key is
/// `rlp(index)`, so the proof is only meaningful together with that index.
pub fn receipts_trie_proof(
    receipts: &[Vec<u8>],
    receipt_index: usize,
) -> Result<Vec<u8>, EvmReceiptError> {
    if receipt_index >= receipts.len() {
        return Err(EvmReceiptError::BadProof);
    }
    let entries = entries_for(receipts);
    let root = build_node(&entries).ok_or(EvmReceiptError::BadProof)?;
    let mut nodes = Vec::new();
    collect_path_nodes(&root, &entries[receipt_index].0, &mut nodes);

    let mut stream = rlp::RlpStream::new_list(nodes.len());
    for node in &nodes {
        stream.append(node);
    }
    Ok(stream.out().to_vec())
}

