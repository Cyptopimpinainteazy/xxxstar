// ── Public error type ──────────────────────────────────────────────────────

/// Errors specific to EVM receipt verification. The `Verifier` trait
/// collapses these into `VerificationError::MalformedProof` (or
/// `UnsupportedChain`) so callers see a unified error surface, but the
/// variants are useful for tests and for richer on-chain event metadata.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum EvmReceiptError {
    /// Payload was too short to contain the wire header.
    TooShort,
    /// The RLP header did not parse.
    BadHeader,
    /// The RLP receipt did not parse.
    BadReceipt,
    /// The Merkle Patricia proof did not parse as a list of node byte
    /// strings.
    BadProof,
    /// The receipt was not included in the asserted receipts root.
    InclusionFailed,
    /// The header this proof is about is not one the chain has attested, so the
    /// proof is about a block of the prover's own choosing.
    UnanchoredHeader,
    /// The receipt did not contain exactly one log.
    WrongLogCount,
    /// The log's first topic did not match the expected event selector.
    BadSelector,
    /// The log data was not decodable as a single uint256 amount.
    BadAmount,
    /// The block has not accumulated enough confirmations.
    InsufficientConfirmations { have: u64, need: u64 },
    /// The receipt was generated by a chain the verifier is not bound to.
    WrongChain { expected: u64, got: u64 },
}

impl From<rlp::DecoderError> for EvmReceiptError {
    fn from(_: rlp::DecoderError) -> Self {
        EvmReceiptError::BadReceipt
    }
}

impl Display for EvmReceiptError {
    fn fmt(&self, f: &mut Formatter<'_>) -> core::fmt::Result {
        match self {
            EvmReceiptError::TooShort => f.write_str("evm proof payload too short"),
            EvmReceiptError::BadHeader => f.write_str("evm proof header is not valid RLP"),
            EvmReceiptError::BadReceipt => f.write_str("evm proof receipt is not valid RLP"),
            EvmReceiptError::BadProof => f.write_str("evm proof inclusion proof is not valid RLP"),
            EvmReceiptError::InclusionFailed => {
                f.write_str("evm proof: receipt not in asserted receipts root")
            }
            EvmReceiptError::WrongLogCount => f.write_str("evm proof: receipt must have 1 log"),
            EvmReceiptError::BadSelector => {
                f.write_str("evm proof: log topic[0] does not match selector")
            }
            EvmReceiptError::BadAmount => f.write_str("evm proof: log data is not uint256 amount"),
            EvmReceiptError::InsufficientConfirmations { have, need } => write!(
                f,
                "evm proof: block confirmations {have} below required {need}"
            ),
            EvmReceiptError::UnanchoredHeader => f.write_str(
                "evm proof: the header is not one the chain has attested",
            ),
            EvmReceiptError::WrongChain { expected, got } => {
                write!(
                    f,
                    "evm proof: chain mismatch (got {got}, expected {expected})"
                )
            }
        }
    }
}

