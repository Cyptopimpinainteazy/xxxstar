/// A decoded wire-format EVM receipt proof.
///
/// Wire layout (everything RLP-encoded, concatenated):
///   * `header`  — 15-element block header, EIP-1186.
///   * `receipt` — receipt RLP bytes (caller-supplied raw receipt).
///   * `receipt_index` — the index of the receipt in the block, as
///     big-endian bytes (the receipt-trie key is `rlp(index)`).
///   * `proof` — Merkle Patricia proof (RLP list of node byte strings).
pub struct DecodedProof {
    pub header: EvmBlockHeader,
    pub receipt: EvmReceipt,
    /// The receipt's RLP bytes, as the wire format carried them.
    ///
    /// Kept because the inclusion walk compares the leaf's stored value against
    /// the receipt: `EvmReceipt` is the decoded form and re-encoding it is not the
    /// same string. The walk was given `None` for the value, and every successful
    /// path in `verify_merkle_patricia_proof` ends in
    /// `Some(stored_value) == value` — `Some(_) == None` is false — so the
    /// verifier rejected every proof it was ever handed (TICKET-064).
    pub receipt_rlp: Vec<u8>,
    pub receipt_index: Vec<u8>,
    pub proof: Vec<u8>,
    pub expected_amount: u128,
    pub expected_recipient: [u8; 20],
    pub expected_selector: [u8; 32],
    pub min_confirmations: u64,
    pub current_block_number: u64,
    pub expected_chain_id: u64,
}

impl DecodedProof {
    pub fn decode(
        payload: &[u8],
        expected_amount: u128,
        expected_recipient: [u8; 20],
        expected_selector: [u8; 32],
        min_confirmations: u64,
        current_block_number: u64,
        expected_chain_id: u64,
    ) -> Result<Self, EvmReceiptError> {
        if payload.len() < 16 {
            return Err(EvmReceiptError::TooShort);
        }
        let mut s = payload;
        let header = take_section(&mut s)?;
        let receipt = take_section(&mut s)?;
        let receipt_index = take_section(&mut s)?;
        let proof = take_section(&mut s)?;
        let header = EvmBlockHeader::decode(&header)?;
        let receipt_decoded = EvmReceipt::decode(&receipt)?;
        Ok(Self {
            header,
            receipt_rlp: receipt,
            receipt: receipt_decoded,
            receipt_index,
            proof,
            expected_amount,
            expected_recipient,
            expected_selector,
            min_confirmations,
            current_block_number,
            expected_chain_id,
        })
    }

    /// The receipt checks: shape, amount, and inclusion in the header's
    /// receipts trie.
    ///
    /// Confirmation depth is **not** checked here. It has to be measured from
    /// the chain's attested head, and a `DecodedProof` carries the prover's own
    /// claim of that head — see [`DecodedProof::validate_against`].
    pub fn validate(&self) -> Result<(), EvmReceiptError> {
        if self.receipt.logs.len() != 1 {
            return Err(EvmReceiptError::WrongLogCount);
        }
        let log = &self.receipt.logs[0];
        if log.address != self.expected_recipient {
            return Err(EvmReceiptError::BadSelector);
        }
        if log.topics.is_empty() || log.topics[0] != self.expected_selector {
            return Err(EvmReceiptError::BadSelector);
        }
        if log.data.len() != 32 {
            return Err(EvmReceiptError::BadAmount);
        }
        let mut buf = [0u8; 32];
        buf.copy_from_slice(&log.data);
        let mut b16 = [0u8; 16];
        b16.copy_from_slice(&buf[16..]);
        let amount = u128::from_be_bytes(b16);
        if amount != self.expected_amount {
            return Err(EvmReceiptError::BadAmount);
        }
        if self.header.number == 0 {
            return Err(EvmReceiptError::BadHeader);
        }
        if self.expected_chain_id == 0 {
            return Err(EvmReceiptError::WrongChain {
                expected: 0,
                got: 0,
            });
        }
        // Receipts-trie key: rlp(receipt_index), from the index bytes the wire
        // format carries. One key builder, so the verifier cannot drift from the
        // convention `receipt_trie_key` states (TICKET-064).
        let key_buf = rlp_index_key(self.receipt_index.as_slice());
        verify_merkle_patricia_proof(
            &self.header.receipts_root,
            &key_buf,
            Some(&self.receipt_rlp),
            &self.proof,
        )?;
        Ok(())
    }

    /// Check the proof against the header the *chain* has attested, then
    /// [`DecodedProof::validate`].
    ///
    /// The header in the payload belongs to the prover: `receipts_root` is what
    /// the walk is checked against and the head height is what the depth was
    /// measured from. Both are fields of the proof, so on their own they establish
    /// only that the proof is self-consistent — a prover builds a trie containing
    /// a receipt they control, names its root, and picks a head height that
    /// satisfies the threshold. The anchor is what makes the header evidence: the
    /// root this proof is checked against, and the head its depth is measured
    /// from, come from the chain's own store.
    pub fn validate_against(
        &self,
        anchor: EvmHeaderAnchorSource,
    ) -> Result<(), EvmReceiptError> {
        let Some(anchored) = anchor.anchored(self.header.number) else {
            return Err(EvmReceiptError::UnanchoredHeader);
        };
        if anchored.receipts_root != self.header.receipts_root {
            return Err(EvmReceiptError::UnanchoredHeader);
        }
        let Some(head) = anchor.head() else {
            return Err(EvmReceiptError::UnanchoredHeader);
        };
        if head < anchored.number {
            // An attested head that predates the header it is meant to bound
            // cannot measure the depth of anything.
            return Err(EvmReceiptError::UnanchoredHeader);
        }
        let confirmations = head.saturating_sub(self.header.number);
        if confirmations < self.min_confirmations {
            return Err(EvmReceiptError::InsufficientConfirmations {
                have: confirmations,
                need: self.min_confirmations,
            });
        }
        self.validate()
    }
}

fn take_section(s: &mut &[u8]) -> Result<Vec<u8>, EvmReceiptError> {
    if s.len() < 4 {
        return Err(EvmReceiptError::TooShort);
    }
    let mut len_bytes = [0u8; 4];
    len_bytes.copy_from_slice(&s[..4]);
    let len = u32::from_be_bytes(len_bytes) as usize;
    if s.len() < 4 + len {
        return Err(EvmReceiptError::TooShort);
    }
    let mut out = Vec::with_capacity(len);
    out.extend_from_slice(&s[4..4 + len]);
    *s = &s[4 + len..];
    Ok(out)
}

fn bytes32(b: &[u8]) -> Result<[u8; 32], EvmReceiptError> {
    if b.len() != 32 {
        return Err(EvmReceiptError::BadHeader);
    }
    let mut out = [0u8; 32];
    out.copy_from_slice(b);
    Ok(out)
}

fn decode_u64(b: &[u8]) -> u64 {
    // Big-endian and *right*-aligned: RLP trims a value's leading zeros, so a
    // short value's bytes belong at the end of the word rather than at the front.
    // Copying them to the front read the header field `100` as
    // `0x6400000000000000`, which made every real header's `number` and
    // `timestamp` absurd — and the confirmations check
    // (`current_block_number - number`) then saturated to zero, so every genuine
    // proof was rejected as insufficiently confirmed. No test noticed because none
    // of them reached this code with a decodable header (TICKET-064).
    let mut buf = [0u8; 8];
    let len = b.len().min(8);
    buf[8 - len..].copy_from_slice(&b[b.len() - len..]);
    u64::from_be_bytes(buf)
}

// ── Proof construction helpers ──────────────────────────────────────────────

/// Encode a wire-format body section: 4-byte big-endian length prefix + data.
/// This is the encoding used by the `take_section` decoder.
#[inline]
pub fn enc_section(buf: &mut alloc::vec::Vec<u8>, data: &[u8]) {
    buf.extend_from_slice(&(data.len() as u32).to_be_bytes());
    buf.extend_from_slice(data);
}

/// The receipts-trie key for a receipt index, from its big-endian bytes.
///
/// The key is `rlp(index)` — the RLP encoding of the *integer*: index 0 is the
/// single byte `0x80`, index 1 is `0x01`, index 128 is `0x81 0x80`. This function
/// used to wrap the index in a list (`rlp([index])`, `0xc1 0x80` for zero), which
/// builds the path of a *different* key: the verifier below then computed a
/// nibble path no standard prover produces, so it could not accept a genuine
/// receipt proof — and its own tests could not notice, because they built their
/// proofs with this same helper. Two facts in the repository say which convention
/// is right: the doc comment on `DecodedProof::receipt_index` ("the receipt-trie
/// key is `rlp(index)`"), and `x3-lang/vm/src/bridge.rs`, whose verifier and whose
/// fixture use the raw encoding (their key for index 1 is the single byte `0x01`)
/// — the two implementations disagreed, and this is the one that was wrong
/// (TICKET-064).
pub fn rlp_index_key(index_be_bytes: &[u8]) -> alloc::vec::Vec<u8> {
    let significant = index_be_bytes
        .iter()
        .position(|byte| *byte != 0)
        .map(|first| &index_be_bytes[first..])
        .unwrap_or(&[]);
    match significant {
        // `rlp(0)` is the empty string's encoding, `0x80`.
        [] => alloc::vec![0x80],
        // A single byte below `0x80` is its own encoding.
        [single] if *single < 0x80 => alloc::vec![*single],
        bytes => {
            let mut out = alloc::vec![0x80 + bytes.len() as u8];
            out.extend_from_slice(bytes);
            out
        }
    }
}

/// Build the receipt-trie key for a given receipt index (`rlp(index)`).
pub fn receipt_trie_key(receipt_index: u64) -> alloc::vec::Vec<u8> {
    rlp_index_key(&receipt_index.to_be_bytes())
}

/// Encode a complete proof payload in the wire format expected by
/// `ProductionEvmReceiptVerifier::verify` / `DecodedProof::decode`.
///
/// Wire format:
///   [8 bytes: current_block_number (little-endian)]
///   [8 bytes: min_confirmations (little-endian)]
///   [body: 4 length-prefixed sections (header_rlp, receipt_rlp, receipt_index, proof)]
///
/// # Arguments
///
/// * `current_block_number` — the current chain head at proof construction time.
/// * `min_confirmations` — the minimum confirmations the verifier will enforce.
/// * `header_rlp` — RLP-encoded EIP-1186 block header (15-element list).
/// * `receipt_rlp` — RLP-encoded transaction receipt.
/// * `receipt_index` — raw bytes of the receipt index (big-endian, variable length).
/// * `proof` — Merkle Patricia trie proof (RLP list of node byte strings).
pub fn encode_proof_payload(
    current_block_number: u64,
    min_confirmations: u64,
    header_rlp: &[u8],
    receipt_rlp: &[u8],
    receipt_index: &[u8],
    proof: &[u8],
) -> alloc::vec::Vec<u8> {
    let mut body = alloc::vec::Vec::with_capacity(
        16 + 4
            + header_rlp.len()
            + 4
            + receipt_rlp.len()
            + 4
            + receipt_index.len()
            + 4
            + proof.len(),
    );
    body.extend_from_slice(&current_block_number.to_le_bytes());
    body.extend_from_slice(&min_confirmations.to_le_bytes());
    enc_section(&mut body, header_rlp);
    enc_section(&mut body, receipt_rlp);
    enc_section(&mut body, receipt_index);
    enc_section(&mut body, proof);
    body
}

/// Compute the keccak256 hash of a 32-byte value using the X3 EVM precompile
/// compatible hash function.
pub fn keccak256_32(input: &[u8]) -> [u8; 32] {
    let mut k = Keccak::v256();
    let mut out = [0u8; 32];
    k.update(input);
    k.finalize(&mut out);
    out
}

